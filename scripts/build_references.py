"""Validate the curated registry and deterministically generate citation exports."""

from __future__ import annotations

import argparse
import csv
import io
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIELDS = ("id", "year", "title", "authors", "venue", "doi", "url", "kind",
          "status", "branch", "evidence", "finding", "limitation", "verification")
KINDS = {"article", "review", "conference", "preprint", "notice"}


def load_sources():
    registry = json.loads((ROOT / "references/sources.json").read_text())
    sources = registry["sources"]
    ids, dois = set(), set()
    for s in sources:
        if set(s) != set(FIELDS):
            raise ValueError(f"Unexpected fields in {s.get('id')}")
        if not re.fullmatch(r"[a-z]+[0-9]{4}", s["id"]) or s["id"] in ids:
            raise ValueError(f"Invalid or duplicate ID: {s['id']}")
        ids.add(s["id"])
        if not isinstance(s["year"], int) or not 1900 <= s["year"] <= 2026:
            raise ValueError(f"Invalid year: {s['id']}")
        for field in set(FIELDS) - {"year", "doi"}:
            if not isinstance(s[field], str) or not s[field].strip():
                raise ValueError(f"Empty or non-string {field}: {s['id']}")
        if s["kind"] not in KINDS or not s["url"].startswith("https://"):
            raise ValueError(f"Invalid kind or URL: {s['id']}")
        doi = s["doi"].lower()
        if doi:
            if not re.fullmatch(r"10\.\d{4,9}/\S+", doi) or doi in dois:
                raise ValueError(f"Invalid or duplicate DOI: {doi}")
            dois.add(doi)
        if s["status"] == "retracted" and "RETRACTED" not in s["limitation"]:
            raise ValueError(f"Retraction warning missing: {s['id']}")
    return registry, sorted(sources, key=lambda s: (s["year"], s["id"]))


def bib_escape(value):
    # UTF-8 BibTeX/BibLaTeX; protect special characters used in these records.
    return value.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def render(registry, sources):
    bib = ["% Generated by scripts/build_references.py; edit sources.json.",
           "% UTF-8; author lists ending in 'and others' are intentionally abbreviated."]
    reading = ["# Annotated reading list", "",
               f"Generated from [sources.json](../references/sources.json); checked {registry['checked']}.",
               "", "Evidence descriptions characterize individual studies, not field-wide validation.", ""]
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(stream, fieldnames=FIELDS, lineterminator="\n")
    writer.writeheader()
    for s in sources:
        writer.writerow(s)
        entry_type = "misc" if s["kind"] in {"preprint", "conference"} else "article"
        title = ("RETRACTED: " if s["status"] == "retracted" else "") + s["title"]
        values = {"title": "{" + bib_escape(title) + "}",
                  "author": bib_escape(s["authors"]), "year": str(s["year"])}
        values["howpublished" if entry_type == "misc" else "journal"] = bib_escape(s["venue"])
        if s["doi"]:
            values["doi"] = s["doi"]
        values["url"] = s["url"]
        values["note"] = bib_escape(f"Status: {s['status']}. {s['limitation']} Checked {registry['checked']}.")
        bib.append(f"\n@{entry_type}{{{s['id']},")
        bib.extend(f"  {key} = {{{value}}}," for key, value in values.items())
        bib.append("}")
        reading.extend([
            f"## {s['id']} — {s['year']} — {s['branch']}", "",
            f"**[{title}]({s['url']})**. {s['authors']}. *{s['venue']}*.", "",
            f"Status: **{s['status']}** · Evidence: {s['evidence']}.", "",
            f"{s['finding']} **Limit:** {s['limitation']}", "",
            f"Verification: {s['verification']}", "",
        ])
    return {
        ROOT / "references/references.bib": "\n".join(bib) + "\n",
        ROOT / "references/literature.csv": stream.getvalue(),
        ROOT / "docs/reading-list.md": "\n".join(reading),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated exports differ")
    args = parser.parse_args()
    registry, sources = load_sources()
    stale = []
    for path, content in render(registry, sources).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        raise SystemExit("Stale exports: " + ", ".join(stale))
    print(f"{'Checked' if args.check else 'Generated'} exports for {len(sources)} sources.")


if __name__ == "__main__":
    main()
